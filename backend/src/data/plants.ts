/**
 * plants.ts — katalog tanaman kebun sayur & buah untuk iklim Indonesia.
 *
 * Bundled, bukan tabel D1 yang di-seed. Alasannya sama dengan
 * `frontend/src/data/holidays.ts`: ini data referensi yang jarang berubah,
 * ditulis tangan dan ditinjau seperti kode, dan harus tetap benar tanpa
 * bergantung pada migration yang berjalan. Menyimpannya di sini juga
 * menghindari seed besar di skrip migrate yang jalan tiap deploy.
 *
 * Angka di sini adalah rentang praktis untuk pekarangan/polybag di Indonesia,
 * bukan angka pertanian komersial. Umur panen dihitung dari tanam benih
 * kecuali `propagation` menyebut bibit/okulasi — untuk pohon buah, umur panen
 * dari bibit okulasi jauh lebih pendek daripada dari biji, dan yang dipakai
 * di sini adalah jalur yang paling umum dipakai pekebun rumahan.
 *
 * Ketinggian mengikuti pembagian yang lazim dipakai penyuluh pertanian:
 *   rendah    = 0–400 mdpl
 *   menengah  = 400–700 mdpl
 *   tinggi    = di atas 700 mdpl
 */

export type PlantCategory =
  | 'sayuran-daun'
  | 'sayuran-buah'
  | 'mikrogreen'
  | 'umbi'
  | 'rempah'
  | 'buah'
  | 'hias-daun'
  | 'hias-bunga'
  | 'sukulen';

export type Sunlight = 'penuh' | 'sebagian' | 'teduh';
export type Difficulty = 'mudah' | 'sedang' | 'sulit';

/**
 * Keterangan yang hanya berlaku untuk tanaman hias.
 *
 * Yang ditanyakan orang tentang aglaonema bukan "kapan panen", melainkan
 * "boleh di dalam rumah?", "beracun tidak kalau digigit kucing?", dan "kenapa
 * daunnya cokelat di pinggir". Pertanyaan itu tidak punya tempat di bentuk
 * data tanaman sayur, jadi dibuatkan tempatnya sendiri alih-alih dititipkan
 * ke kolom yang artinya lain.
 */
export interface OrnamentalInfo {
  /** Bertahan di dalam ruangan dengan cahaya tidak langsung. */
  indoor: boolean;
  /**
   * Kapan dan bagaimana berbunga; null untuk yang ditanam demi daunnya.
   * Menjanjikan bunga pada tanaman daun adalah janji yang tidak akan ditepati.
   */
  bloom: string | null;
  /**
   * Beracun bila termakan atau getahnya kena kulit.
   *
   * Ini satu-satunya kolom di berkas ini yang bisa berujung ke ruang gawat
   * darurat: aglaonema, dieffenbachia, dan philodendron ada di hampir setiap
   * rumah dan semuanya beracun bagi anak dan hewan peliharaan. Karena itu
   * nilainya selalu diisi eksplisit, tidak pernah dibiarkan kosong dan
   * diartikan "aman".
   */
  toxic: boolean;
  /** Catatan racunnya — apa yang beracun dan seberapa. */
  toxicNote: string;
  /** Perawatan rutin yang menentukan penampilannya tetap bagus. */
  grooming: string;
}

export interface Plant {
  /** Slug stabil — dipakai sebagai foreign key di garden_plantings. */
  id: string;
  name: string;
  latinName: string;
  category: PlantCategory;
  emoji: string;
  /**
   * Umur panen dalam hari: [tercepat, terlama]. `null` untuk tanaman hias.
   *
   * Null, bukan angka besar atau nol. Mawar tidak dipanen, dan mengisi kolom
   * ini dengan angka apa pun akan membuat aplikasi mengumumkan "mawarmu siap
   * panen", mengirim pengingat panen, lalu memasukkannya ke hitungan HPP per
   * kilogram — tiga fitur yang salah sekaligus, tanpa satu pun pesan galat.
   * Dengan null, setiap tempat yang mengandaikan panen harus menyebutkannya
   * secara eksplisit, dan pemeriksa tipe yang menagihnya.
   */
  daysToHarvest: [number, number] | null;
  /**
   * Tanaman yang dipanen berulang (cabai, tomat, kacang panjang) vs sekali
   * cabut (kangkung, bayam, wortel). Menentukan apakah jadwal panen berhenti
   * setelah panen pertama atau berulang tiap `harvestEveryDays`.
   */
  repeatHarvest: boolean;
  /** Jarak antar panen untuk tanaman panen berulang, hari. */
  harvestEveryDays: number | null;
  /** Interval siram normal di musim kemarau, hari. */
  waterIntervalDays: number;
  waterNote: string;
  /** Interval pemupukan susulan, hari. */
  fertilizeIntervalDays: number;
  fertilizer: string;
  sunlight: Sunlight;
  /** Jarak tanam antar tanaman, cm. */
  spacingCm: number;
  /** Volume pot/polybag minimum, liter. 0 = tidak cocok di pot. */
  potLiter: number;
  difficulty: Difficulty;
  /** Musim tanam terbaik di Indonesia. */
  season: string;
  /** Rentang pH tanah ideal. */
  phRange: [number, number];
  altitude: string;
  pests: string[];
  companions: string[];
  /** Tanaman yang sebaiknya tidak berdekatan. */
  avoid: string[];
  propagation: string;
  harvestNote: string;
  tips: string;
  /**
   * Aturan pangkas — hanya untuk tanaman yang pangkasnya benar-benar
   * menentukan hasil.
   *
   * Opsional dengan sengaja. Kebanyakan sayuran daun tidak dipangkas sama
   * sekali, dan mengisi kolom ini untuk seluruh katalog berarti menebak —
   * tebakan yang tampil seyakin fakta lebih buruk daripada kolom yang kosong.
   * Diisi hanya untuk tanaman yang aturannya disepakati luas dan dampaknya
   * pada hasil sudah jelas.
   *
   * Tanaman hias tidak pernah diberi kolom ini: perawatan bentuknya sudah
   * punya tempat sendiri di `ornamental.grooming`, dan dua sumber aturan untuk
   * hal yang sama akan saling bertentangan diam-diam.
   */
  pruning?: {
    /** Hari sejak tanam sebelum pangkas pertama masuk akal. */
    mulaiHari: number;
    /** Jarak antar pangkas sesudahnya, hari. */
    ulangHari: number;
    catatan: string;
  };
  /** Terisi hanya untuk tanaman hias; tidak ada untuk tanaman pangan. */
  ornamental?: OrnamentalInfo;
}

/** Tanaman pangan yang punya umur panen. */
export type HarvestablePlant = Plant & { daysToHarvest: [number, number] };

/**
 * Benar bila tanaman ini memang dipanen.
 *
 * Dipakai sebagai penjaga sebelum menyentuh `daysToHarvest`, dan bentuknya
 * type predicate supaya pemeriksa tipe ikut menyempitkan — kalau ada tempat
 * yang lupa memeriksa, ketahuan saat kompilasi, bukan saat pengguna melihat
 * pengingat panen untuk mawarnya.
 */
export function dipanen(plant: Plant): plant is HarvestablePlant {
  return plant.daysToHarvest !== null;
}

/** Benar untuk tanaman hias — yang ditanam demi tampilannya, bukan hasilnya. */
export function tanamanHias(plant: Plant): boolean {
  return plant.ornamental !== undefined;
}

